import assert from "node:assert/strict";
import {
  mkdir,
  readFile,
  readdir,
  writeFile,
} from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";


const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const webRoot = resolve(scriptDirectory, "..");
const repositoryRoot = resolve(webRoot, "..", "..");
const snapshotPath = resolve(
  repositoryRoot,
  "contracts",
  "api",
  "openapi.json",
);
const outputDirectory = resolve(
  webRoot,
  "src",
  "generated",
  "api-client",
);
const generatedHeader = [
  "// @generated",
  "// Source: contracts/api/openapi.json",
  "// Command: npm --prefix apps/web run generate:api",
  "// Do not edit this file by hand.",
  "",
].join("\n");
const httpMethods = [
  "get",
  "put",
  "post",
  "delete",
  "options",
  "head",
  "patch",
  "trace",
];


function normalizeNewlines(value) {
  return value.replaceAll("\r\n", "\n").replaceAll("\r", "\n");
}


function indent(value, count = 2) {
  const prefix = " ".repeat(count);
  return value
    .split("\n")
    .map((line) => (line.length > 0 ? prefix + line : line))
    .join("\n");
}


function localReferenceType(reference) {
  const prefix = "#/components/schemas/";
  if (!reference.startsWith(prefix)) {
    throw new Error("Unsupported OpenAPI reference: " + reference);
  }
  const name = decodeURIComponent(reference.slice(prefix.length));
  return 'components["schemas"][' + JSON.stringify(name) + "]";
}


function schemaType(schema) {
  if (schema === true || schema === undefined) {
    return "unknown";
  }
  if (schema === false) {
    return "never";
  }
  if (schema.$ref) {
    return localReferenceType(schema.$ref);
  }
  if (Object.hasOwn(schema, "const")) {
    return JSON.stringify(schema.const);
  }
  if (Array.isArray(schema.enum)) {
    return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  }
  if (Array.isArray(schema.oneOf)) {
    return schema.oneOf.map(schemaType).join(" | ");
  }
  if (Array.isArray(schema.anyOf)) {
    return schema.anyOf.map(schemaType).join(" | ");
  }
  if (Array.isArray(schema.allOf)) {
    return schema.allOf.map(schemaType).join(" & ");
  }
  if (Array.isArray(schema.type)) {
    return schema.type
      .map((type) => schemaType({ ...schema, type }))
      .join(" | ");
  }
  let result;
  switch (schema.type) {
    case "null":
      result = "null";
      break;
    case "boolean":
      result = "boolean";
      break;
    case "integer":
    case "number":
      result = "number";
      break;
    case "string":
      result = "string";
      break;
    case "array":
      result = "ReadonlyArray<" + schemaType(schema.items) + ">";
      break;
    case "object":
    default:
      if (
        schema.type === "object" ||
        schema.properties ||
        schema.additionalProperties
      ) {
        result = objectType(schema);
      } else {
        result = "unknown";
      }
      break;
  }
  return schema.nullable ? result + " | null" : result;
}


function objectType(schema) {
  const required = new Set(schema.required ?? []);
  const members = Object.entries(schema.properties ?? {})
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([name, value]) => {
      const optional = required.has(name) ? "" : "?";
      return (
        "readonly " +
        JSON.stringify(name) +
        optional +
        ": " +
        schemaType(value) +
        ";"
      );
    });
  if (schema.additionalProperties === true) {
    members.push("readonly [key: string]: unknown;");
  } else if (
    schema.additionalProperties &&
    typeof schema.additionalProperties === "object"
  ) {
    members.push(
      "readonly [key: string]: " +
        schemaType(schema.additionalProperties) +
        ";",
    );
  }
  if (members.length === 0) {
    return schema.additionalProperties === false
      ? "Record<string, never>"
      : "Record<string, unknown>";
  }
  return "{\n" + indent(members.join("\n")) + "\n}";
}


function dereference(document, value) {
  if (!value || !value.$ref) {
    return value;
  }
  if (!value.$ref.startsWith("#/")) {
    throw new Error("Only local OpenAPI references are supported.");
  }
  return value.$ref
    .slice(2)
    .split("/")
    .reduce(
      (current, part) =>
        current[
          part.replaceAll("~1", "/").replaceAll("~0", "~")
        ],
      document,
    );
}


function contentType(content) {
  if (!content || Object.keys(content).length === 0) {
    return "never";
  }
  const members = Object.entries(content)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(
      ([mediaType, media]) =>
        "readonly " +
        JSON.stringify(mediaType) +
        ": " +
        schemaType(media.schema) +
        ";",
    );
  return "{\n" + indent(members.join("\n")) + "\n}";
}


function parameterType(document, parameters) {
  const groups = new Map([
    ["query", []],
    ["header", []],
    ["path", []],
    ["cookie", []],
  ]);
  for (const unresolved of parameters) {
    const parameter = dereference(document, unresolved);
    if (!groups.has(parameter.in)) {
      continue;
    }
    groups.get(parameter.in).push(parameter);
  }
  const members = [];
  for (const [location, values] of groups) {
    if (values.length === 0) {
      members.push("readonly " + location + "?: never;");
      continue;
    }
    const fields = values
      .sort((left, right) => left.name.localeCompare(right.name))
      .map((parameter) => {
        const optional = parameter.required ? "" : "?";
        return (
          "readonly " +
          JSON.stringify(parameter.name) +
          optional +
          ": " +
          schemaType(parameter.schema) +
          ";"
        );
      });
    const groupOptional = values.some((value) => value.required) ? "" : "?";
    members.push(
      "readonly " +
        location +
        groupOptional +
        ": {\n" +
        indent(fields.join("\n"), 4) +
        "\n  };",
    );
  }
  return "{\n" + indent(members.join("\n")) + "\n}";
}


function responseType(document, unresolved) {
  const response = dereference(document, unresolved);
  const content = contentType(response.content);
  const contentMember =
    content === "never"
      ? "readonly content?: never;"
      : "readonly content: " + content + ";";
  return (
    "{\n" +
    indent(
      "readonly headers: Record<string, unknown>;\n" + contentMember,
    ) +
    "\n}"
  );
}


function operationType(document, pathItem, operation) {
  const parameterMap = new Map();
  for (const parameter of [
    ...(pathItem.parameters ?? []),
    ...(operation.parameters ?? []),
  ]) {
    const resolved = dereference(document, parameter);
    parameterMap.set(resolved.in + ":" + resolved.name, parameter);
  }
  const members = [
    "readonly parameters: " +
      parameterType(document, [...parameterMap.values()]) +
      ";",
  ];
  if (operation.requestBody) {
    const body = dereference(document, operation.requestBody);
    const optional = body.required ? "" : "?";
    members.push(
      "readonly requestBody" +
        optional +
        ": {\n" +
        indent("readonly content: " + contentType(body.content) + ";", 4) +
        "\n  };",
    );
  } else {
    members.push("readonly requestBody?: never;");
  }
  const responses = Object.entries(operation.responses ?? {})
    .sort(([left], [right]) => left.localeCompare(right))
    .map(
      ([status, response]) =>
        "readonly " +
        (/^\d+$/.test(status) ? status : JSON.stringify(status)) +
        ": " +
        responseType(document, response) +
        ";",
    );
  members.push(
    "readonly responses: {\n" +
      indent(responses.join("\n"), 4) +
      "\n  };",
  );
  return "{\n" + indent(members.join("\n")) + "\n}";
}


function generateSchema(document) {
  const schemas = Object.entries(document.components?.schemas ?? {})
    .sort(([left], [right]) => left.localeCompare(right))
    .map(
      ([name, schema]) =>
        "readonly " +
        JSON.stringify(name) +
        ": " +
        schemaType(schema) +
        ";",
    );
  const operations = [];
  const paths = [];
  for (const [path, pathItem] of Object.entries(document.paths ?? {}).sort(
    ([left], [right]) => left.localeCompare(right),
  )) {
    const pathMembers = [
      "readonly parameters: " +
        parameterType(document, pathItem.parameters ?? []) +
        ";",
    ];
    for (const method of httpMethods) {
      const operation = pathItem[method];
      if (!operation) {
        continue;
      }
      assert.match(
        operation.operationId,
        /^[A-Za-z_$][A-Za-z0-9_$]*$/,
        "Every generated operation needs a TypeScript-safe operationId.",
      );
      operations.push(
        "readonly " +
          operation.operationId +
          ": " +
          operationType(document, pathItem, operation) +
          ";",
      );
      pathMembers.push(
        "readonly " +
          method +
          ": operations[" +
          JSON.stringify(operation.operationId) +
          "];",
      );
    }
    paths.push(
      "readonly " +
        JSON.stringify(path) +
        ": {\n" +
        indent(pathMembers.join("\n"), 4) +
        "\n  };",
    );
  }
  return [
    "export interface paths {",
    indent(paths.join("\n")),
    "}",
    "",
    "export type webhooks = Record<string, never>;",
    "",
    "export interface components {",
    "  readonly schemas: {",
    indent(schemas.join("\n"), 4),
    "  };",
    "  readonly responses: never;",
    "  readonly parameters: never;",
    "  readonly requestBodies: never;",
    "  readonly headers: never;",
    "  readonly pathItems: never;",
    "}",
    "",
    "export interface operations {",
    indent(operations.join("\n")),
    "}",
    "",
  ].join("\n");
}


async function expectedOutputs() {
  const source = await readFile(snapshotPath, "utf8");
  const document = JSON.parse(source);
  assert.equal(document.openapi, "3.1.0");
  const schema = generatedHeader + generateSchema(document);
  const client = generatedHeader + [
    'import createClient from "openapi-fetch";',
    'import type { paths } from "./schema";',
    "",
    "export type FinancialAcademyApiClient = ReturnType<",
    "  typeof createFinancialAcademyApiClient",
    ">;",
    "",
    "export function createFinancialAcademyApiClient(baseUrl: string) {",
    "  return createClient<paths>({",
    "    baseUrl,",
    '    credentials: "same-origin",',
    "  });",
    "}",
    "",
  ].join("\n");
  const index = generatedHeader + [
    'export { createFinancialAcademyApiClient } from "./client";',
    'export type { FinancialAcademyApiClient } from "./client";',
    'export type { components, operations, paths } from "./schema";',
    "",
  ].join("\n");
  return new Map([
    [resolve(outputDirectory, "schema.d.ts"), schema],
    [resolve(outputDirectory, "client.ts"), client],
    [resolve(outputDirectory, "index.ts"), index],
  ]);
}


async function checkOutputs(outputs) {
  const stale = [];
  for (const [path, expected] of outputs) {
    let actual;
    try {
      actual = await readFile(path, "utf8");
    } catch (error) {
      if (error && error.code === "ENOENT") {
        stale.push(path);
        continue;
      }
      throw error;
    }
    if (normalizeNewlines(actual) !== expected) {
      stale.push(path);
    }
  }
  if (stale.length > 0) {
    throw new Error(
      "Generated API client is stale:\n" +
        stale.map((path) => "- " + path).join("\n"),
    );
  }
}


async function writeOutputs(outputs) {
  await mkdir(outputDirectory, { recursive: true });
  for (const [path, expected] of outputs) {
    let actual = null;
    try {
      actual = normalizeNewlines(await readFile(path, "utf8"));
    } catch (error) {
      if (!error || error.code !== "ENOENT") {
        throw error;
      }
    }
    if (actual !== expected) {
      await writeFile(path, expected, "utf8");
      console.log("Wrote " + path);
    }
  }
}


async function runContractTests(outputs) {
  await checkOutputs(outputs);
  const testDirectory = resolve(webRoot, "tests", "contract");
  const files = (await readdir(testDirectory))
    .filter((name) => name.endsWith(".test.mjs"))
    .sort();
  assert.ok(files.length > 0, "No generated-client contract tests found.");
  for (const file of files) {
    await import(pathToFileURL(resolve(testDirectory, file)).href);
    console.log("Passed " + file);
  }
}


const argumentsList = process.argv.slice(2);
const command = argumentsList[0] === "test" ? "test" : "generate";
const checkOnly = argumentsList.includes("--check");
const outputs = await expectedOutputs();
if (command === "test") {
  await runContractTests(outputs);
} else if (checkOnly) {
  await checkOutputs(outputs);
  console.log("Generated API client is current.");
} else {
  await writeOutputs(outputs);
}
