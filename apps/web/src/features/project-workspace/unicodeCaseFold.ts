function foldCodePoint(codePoint: number): readonly number[] {
  const full = FULL_CASE_FOLDS.get(codePoint);
  if (full) return full;
  const simple = SIMPLE_CASE_FOLDS.get(codePoint);
  if (simple !== undefined) return [simple];
  for (const [start, end, step, offset] of SIMPLE_CASE_FOLD_RANGES) {
    if (codePoint >= start && codePoint <= end && (codePoint - start) % step === 0) {
      return [codePoint + offset];
    }
  }
  return [codePoint];
}

export function unicodeCaseFold16(value: string): string {
  return [...value.normalize("NFC")]
    .flatMap((character) => foldCodePoint(character.codePointAt(0)!))
    .map((codePoint) => String.fromCodePoint(codePoint))
    .join("");
}
